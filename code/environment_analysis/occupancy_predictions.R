suppressMessages(library(unmarked))
r <- normalizePath('Birds')
out <- file.path(r,'results/environment_analysis')
Y <- as.matrix(read.csv(file.path(r,'results/baseline/occ_y_NDVI_author.csv')))
SC <- read.csv(file.path(r,'results/baseline/occ_sitecovs_NDVI_author.csv'))
per <- rep(c('Pre-Maria','Inter-Hurricanes','Post-Fiona'),each=3)
lev <- c('Inter-Hurricanes','Post-Fiona','Pre-Maria')
sc <- data.frame(Elevation=SC$elev_z,NDVI=SC$veg_z)
oc <- data.frame(Period=factor(rep(per,times=nrow(Y)),levels=lev))
umf <- unmarkedMultFrame(y=Y,numPrimary=3,siteCovs=sc,obsCovs=oc)
fm <- colext(~Elevation+NDVI,~NDVI,~Elevation+NDVI,~Period,data=umf,method='BFGS',se=TRUE,control=list(maxit=10000,trace=0))
stopifnot(fm@opt$convergence==0)
res <- do.call(rbind,lapply(c('psi','col','ext','det'),function(k){s<-summary(fm[k]);data.frame(component=k,parameter=rownames(s),s,row.names=NULL)}))
names(res)<-c('component','parameter','estimate','SE','z','p')
old<-read.csv(file.path(r,'results/baseline/occupancy_ordering_test.csv'));old<-old[old$mode=='site_major',]
stopifnot(max(abs(res$estimate-old$estimate))<1e-4)
write.csv(res,file.path(out,'occupancy_refit_coefficients.csv'),row.names=FALSE)
write.csv(vcov(fm),file.path(out,'occupancy_covariance.csv'))
write.csv(data.frame(name=names(coef(fm)),estimate=coef(fm)),file.path(out,'occupancy_coefficient_order.csv'),row.names=FALSE)
pr<-SC
for(k in c('psi','col','ext')){p<-predict(fm,type=k,newdata=sc);for(n in names(p))pr[[paste(k,n,sep='_')]]<-p[[n]]}
write.csv(pr,file.path(out,'occupancy_site_predictions.csv'),row.names=FALSE)
saveRDS(fm,file.path(out,'occupancy_corrected_refit.rds'))
writeLines(paste('AIC',fm@AIC,'max_coefficient_difference',max(abs(res$estimate-old$estimate))),file.path(out,'occupancy_refit_validation.txt'))
cat('Corrected refit validated; AIC',fm@AIC,'sites',nrow(Y),'\n')
